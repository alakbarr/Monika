"""
Base typing infrastructure for modular Telegram bot mixins.
Provides static attribute and cross-mixin method declarations during type-checking
without introducing runtime overhead or metaclass conflicts.
"""

from typing import TYPE_CHECKING, Any, Dict, List, Optional, Set, Tuple

if TYPE_CHECKING:
    import asyncio
    from telegram import InlineKeyboardMarkup, Update
    from telegram.ext import Application, ContextTypes

    from monika.interfaces.telegram.chat_agent import ChatAgent
    from monika.interfaces.telegram.command_router import CommandRouter
    from monika.interfaces.telegram.topic_manager import TopicManager
    from monika.interfaces.telegram.voice_handler import VoiceHandler


class _TelegramBotMixinBase:
    """
    Type-checking base class for TelegramBot mixins.
    Attributes and cross-mixin methods are only declared during static analysis.
    At runtime, this class is an empty lightweight base.
    """

    if TYPE_CHECKING:
        settings: Any
        execution_service: Any
        cycle_scheduler: Any
        _activity_log: Optional[Any]
        task_registry: Optional[Any]
        token: str
        admin_chat_id: int
        allowed_user_ids: Set[int]
        _chat_agents: Dict[Any, Any]
        topic_manager: Any
        voice_handler: Any
        _router: Any
        _is_running: bool
        _outbound_queue: Any
        _outbound_worker_task: Optional[Any]
        _last_send_global: float
        _last_send_per_chat: Dict[int, float]
        _offline_queue_file: str
        _app: Optional[Any]
        _active_nonces: Dict[str, Any]
        _fallback_events: Dict[str, Any]
        _fallback_results: Dict[str, dict]

        # Auth & Helper predicates
        def _is_authorized(self, update: Any) -> bool: ...
        def _is_admin(self, update: Any) -> bool: ...
        async def _reject_unauthorized(self, update: Any) -> None: ...
        async def _reject_non_admin(self, update: Any) -> None: ...
        async def _resolve_action_agent(self, user_id: int, action_id: str, query: Any) -> Optional[Any]: ...
        async def _run_cycle_and_notify(self, update: Any) -> None: ...
        async def _run_backtest_and_notify(
            self, update: Any, days: int, mode: str = "full", initial_equity: float = 10000.0
        ) -> None: ...
        async def _monitor_pending_expiry(
            self, msg: Any, action_id: str, agent: Any, timeout: float = 90.0
        ) -> None: ...

        # Cross-mixin command methods
        async def _cmd_closeall(self, update: Any, ctx: Any) -> Any: ...

        # Queue / Sending methods
        async def _enqueue_outbound(self, *args: Any, **kwargs: Any) -> Any: ...
        async def _send_direct_or_split(self, *args: Any, **kwargs: Any) -> Any: ...

        # Chunking / Formatters
        @staticmethod
        def _chunk_text(
            text: str,
            max_len: int = 4000,
            sanitize_format: bool = False,
            is_html: bool = False,
        ) -> List[str]: ...
        @staticmethod
        def _balance_markdown_chunk(chunk: str) -> str: ...
        @staticmethod
        def _balance_html_chunk(chunk: str) -> Tuple[str, str]: ...

        # Build text methods
        async def _build_status_text(self) -> str: ...
        async def _build_positions_text(self) -> str: ...
        async def _build_brief_text(self) -> str: ...
        async def _build_analysis_text(self, symbol: str) -> str: ...
        async def _build_history_text(self) -> str: ...
        async def _build_risk_text(self) -> str: ...
        async def _build_risk_deep_text(self) -> str: ...
        async def _build_pipeline_text(self) -> str: ...
        async def _build_approvals_text(self) -> str: ...
        async def _build_trailing_text(self) -> str: ...
        async def _build_reconcile_text(self) -> str: ...
        async def _build_fedwatch_text(self) -> str: ...
        async def _build_yields_text(self) -> str: ...
        async def _build_fear_greed_text(self) -> str: ...
        async def _build_cot_text(self, market_code: Optional[str] = None) -> str: ...
        async def _build_playbooks_text(self) -> str: ...
        async def _build_rollback_text(self, name: str) -> str: ...
        async def _build_crystallized_text(self) -> str: ...
        async def _build_vix_text(self) -> str: ...
        async def _build_tokens_text(self) -> str: ...
        async def _build_credits_text(self) -> str: ...
        async def _build_stats_text(self) -> str: ...
        def _build_plugins_text(self, plugins: list[dict]) -> str: ...
        def _build_plugins_keyboard(self, plugins: list[dict]) -> Any: ...
        async def _build_weekly_report(self) -> str: ...


__all__ = ["_TelegramBotMixinBase"]
